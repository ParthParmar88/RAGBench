"""Build the evaluation benchmark from the ingested corpus.

    python -m evaluation.generate_dataset

Questions are generated *from real passages*, so every ground truth is traceable
to text that actually exists. Each generated case is immediately checked: the
supporting quote must appear verbatim in the passage it came from. Paraphrased
quotes are retried once, then dropped.

Known limitation, stated plainly: questions are generated by the same model
family that answers them (gpt-4o-mini). That risks a benchmark shaped to the
model's own phrasing habits, which flatters it. Two things mitigate it — the
adversarial categories are hand-written, not generated, and the quote check
grounds every case in source text rather than model recall. It remains a real
caveat and belongs in the final write-up.
"""
import argparse
import random
import re
from dataclasses import dataclass

from pydantic import BaseModel, Field
from sqlalchemy import select

from app.config import settings
from app.database import SessionLocal
from app.models import Document, KnowledgeUnit
from app.services import llm
from app.services.llm import UsageContext
from evaluation.dataset.handwritten import HANDWRITTEN
from evaluation.dataset.schema import TestCase, quote_found_in, save_dataset

SEED = 20260814  # fixed so regeneration samples the same passages

# How many to generate per category. Weighted toward `keyword`: that is the
# category Experiment 003 must move, so it needs enough cases to show a signal
# above noise.
TARGETS = {
    "factual": 16,
    # Also over-requested: semantic questions must avoid the source's vocabulary,
    # and the easiest way to do that is to say "the passage" — which the
    # self-containment filter rejects. Highest rejection rate of the singles.
    "semantic": 18,
    "keyword": 18,
    # Over-requested: pairs reject at roughly twice the rate of single-passage
    # cases (both quotes must verify), and these two categories carry the
    # Experiment 002 and 004 signals, so a thin sample would leave those
    # experiments unable to distinguish a real effect from noise.
    "multi_chunk": 20,
    "multi_document": 15,
}

# Cross-document pairs chosen for genuine comparability. Random pairs produce
# contrived questions ("how does positional encoding relate to NDCG?") that test
# nothing.
DOC_PAIRS = [
    ("dpr.pdf", "colbert.pdf"),
    ("attention.pdf", "bert.pdf"),
    ("rag.pdf", "dpr.pdf"),
    ("reranking.pdf", "colbert.pdf"),
    ("beir.pdf", "dpr.pdf"),
    ("lostinthemiddle.pdf", "reranking.pdf"),
]

SELF_CONTAINED_RULE = (
    "The question must stand completely on its own, as a real user would ask it "
    "of a search system that has never seen these passages. NEVER refer to 'the "
    "passage', 'Passage A', 'Passage B', 'the text above', or 'this excerpt'. "
    "Name the actual subject instead — e.g. 'How does ColBERT's late interaction "
    "differ from DPR's dual encoder?', not 'How does the method in Passage A "
    "differ from Passage B?'. Do not ask about authors, citations, arXiv "
    "identifiers, or publication venues; ask about technical content."
)

QUOTE_RULE = (
    "The supporting quote MUST be copied character-for-character from the "
    "passage — one or two contiguous sentences. Do not paraphrase, summarise, "
    "reformat, fix typos, or join text across a gap. Do NOT add ellipses ('...') "
    "at the start or end; begin and end at a real word in the passage. It is "
    "checked against the source and rejected if it does not match."
)

PROMPTS = {
    "factual": (
        "Write one specific factual question answerable from this passage alone. "
        "It must have a definite answer stated in the text (a number, name, "
        "method, or result) — not an opinion or a summary request."
    ),
    "semantic": (
        "Write one conceptual question that this passage answers, deliberately "
        "using DIFFERENT vocabulary from the passage. Avoid reusing its "
        "distinctive nouns and technical terms; describe the idea in other "
        "words. The question must still be clearly answerable from the passage."
    ),
    "keyword": (
        "Identify the rarest, most specific identifier in this passage — a model "
        "name, dataset, metric, function, or acronym — and write a question that "
        "turns on that exact term. Someone searching for the term by keyword "
        "should find this passage; someone searching by topic alone might not."
    ),
    "multi_chunk": (
        "Write one question that requires BOTH passages to answer fully. "
        "Answering from only one must leave the answer incomplete. Both passages "
        "come from the same paper."
    ),
    "multi_document": (
        "Write one comparison question that requires BOTH passages, which come "
        "from DIFFERENT papers. It must genuinely need both — a question "
        "answerable from either alone does not test multi-document retrieval."
    ),
}


class SingleCase(BaseModel):
    question: str = Field(..., description="The question to ask the RAG system.")
    ground_truth: str = Field(..., description="The correct answer, 1-3 sentences.")
    supporting_quote: str = Field(..., description="Verbatim text from the passage.")


class PairCase(BaseModel):
    question: str
    ground_truth: str
    supporting_quote_a: str = Field(..., description="Verbatim, from passage A.")
    supporting_quote_b: str = Field(..., description="Verbatim, from passage B.")


@dataclass
class Passage:
    doc: str
    text: str


# --- passage filtering -----------------------------------------------------
# Bibliographies generate worthless questions ("what is the arXiv identifier of
# the 2017 summarization preprint?"), which test citation-list lookup rather
# than comprehension and add noise that masks real retrieval effects.
_YEAR = re.compile(r"\b(19|20)\d{2}\b")
_VENUE = re.compile(r"arXiv[:\s]|In (Proceedings|Advances|Conference)", re.I)

# Measured against this corpus: reference lists carry BOTH dense years and dense
# venue markers, while "Related Work" prose is year-dense but venue-free. Testing
# both discriminates the two — a year-only threshold would discard valid prose.
_YEARS_PER_1K = 6.0
_VENUES_PER_1K = 2.0


def is_reference_section(text: str) -> bool:
    per_1k = max(len(text), 1) / 1000
    years = len(_YEAR.findall(text)) / per_1k
    venues = len(_VENUE.findall(text)) / per_1k
    return years >= _YEARS_PER_1K and venues >= _VENUES_PER_1K


# The generator sees passages labelled "A" and "B"; that scaffold must never
# reach the question. A question mentioning "Passage A" is unanswerable by a
# real user and by the RAG system, which has no such concept.
_SCAFFOLD_LEAK = re.compile(
    r"\bpassages?\s*[ab]\b|\b(the|this|that|each|both|first|second)\s+"
    r"(passages?|excerpts?)\b|\bin\s+the\s+(passages?|excerpts?|text\s+above)\b",
    re.I,
)


def leaks_scaffold(question: str) -> bool:
    return bool(_SCAFFOLD_LEAK.search(question))


def load_corpus(db) -> dict[str, list[Passage]]:
    rows = db.execute(
        select(Document.title, KnowledgeUnit.content, KnowledgeUnit.chunk_index)
        .join(KnowledgeUnit, KnowledgeUnit.document_id == Document.id)
        .order_by(Document.title, KnowledgeUnit.chunk_index)
    ).all()
    corpus: dict[str, list[Passage]] = {}
    for title, content, _ in rows:
        if is_reference_section(content):
            continue
        corpus.setdefault(title, []).append(Passage(title, content))
    return corpus


def _generate(system: str, user: str, schema, usage: UsageContext):
    completion = llm.chat_parse(
        model=settings.OPENAI_MODEL,
        messages=[
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
        response_format=schema,
        operation="dataset_generation",
        usage=usage,
    )
    return completion.choices[0].message.parsed


def generate_single(category: str, passage: Passage, usage: UsageContext):
    system = (
        f"You write evaluation questions for a retrieval system.\n\n"
        f"{PROMPTS[category]}\n\n{SELF_CONTAINED_RULE}\n\n{QUOTE_RULE}"
    )
    return _generate(system, f"Passage:\n\n{passage.text}", SingleCase, usage)


def generate_pair(category: str, a: Passage, b: Passage, usage: UsageContext):
    system = (
        f"You write evaluation questions for a retrieval system.\n\n"
        f"{PROMPTS[category]}\n\n{SELF_CONTAINED_RULE}\n\n{QUOTE_RULE}"
    )
    user = (
        f"Passage A (from {a.doc}):\n\n{a.text}\n\n"
        f"---\n\nPassage B (from {b.doc}):\n\n{b.text}"
    )
    return _generate(system, user, PairCase, usage)


def build_single(category: str, passage: Passage, usage, attempts: int = 3):
    """Generate one case, retrying if the quote was not copied verbatim."""
    for _ in range(attempts):
        result = generate_single(category, passage, usage)
        if not result:
            continue
        if leaks_scaffold(result.question):
            continue
        if quote_found_in(result.supporting_quote, [passage.text]):
            return result, None
    return None, "quote not verbatim or question not self-contained"


# Pairs need BOTH quotes verbatim, so a ~10% per-quote failure rate compounds
# into a ~20% pair failure rate. More attempts, not a weaker check: rejection is
# catching genuinely fabricated quotes, which is the point.
def build_pair(category: str, a: Passage, b: Passage, usage, attempts: int = 4):
    for _ in range(attempts):
        result = generate_pair(category, a, b, usage)
        if not result:
            continue
        if leaks_scaffold(result.question):
            continue
        if quote_found_in(result.supporting_quote_a, [a.text]) and quote_found_in(
            result.supporting_quote_b, [b.text]
        ):
            return result, None
    return None, "quote not verbatim or question not self-contained"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--limit", type=int, help="cap per category (for a dry run)")
    args = parser.parse_args()

    rng = random.Random(SEED)
    db = SessionLocal()
    try:
        corpus = load_corpus(db)
    finally:
        db.close()

    if not corpus:
        raise SystemExit("Corpus is empty — run `python -m evaluation.ingest_corpus`.")

    docs = sorted(corpus)
    usage = UsageContext(request_id="dataset-generation")
    cases: list[TestCase] = []
    rejected: list[str] = []
    counter = 0

    def next_id() -> str:
        nonlocal counter
        counter += 1
        return f"q{counter:03d}"

    # --- single-passage categories, sampled evenly across documents ---------
    for category in ("factual", "semantic", "keyword"):
        target = min(TARGETS[category], args.limit or TARGETS[category])
        picks = [
            rng.choice(corpus[docs[i % len(docs)]]) for i in range(target)
        ]
        for passage in picks:
            result, error = build_single(category, passage, usage)
            if error:
                rejected.append(f"{category}: {error}")
                continue
            cases.append(
                TestCase(
                    id=next_id(),
                    question=result.question,
                    ground_truth=result.ground_truth,
                    category=category,
                    relevant_docs=[passage.doc],
                    supporting_quotes=[result.supporting_quote],
                )
            )
        print(f"  {category:16} {sum(c.category == category for c in cases):>3}")

    # --- two passages from the same paper -----------------------------------
    target = min(TARGETS["multi_chunk"], args.limit or TARGETS["multi_chunk"])
    for i in range(target):
        doc = docs[i % len(docs)]
        passages = corpus[doc]
        if len(passages) < 4:
            continue
        # Nearby but not adjacent: adjacent chunks overlap by 150 chars, so a
        # question spanning them could be answered by either one alone.
        start = rng.randrange(0, len(passages) - 3)
        a, b = passages[start], passages[start + 3]
        result, error = build_pair("multi_chunk", a, b, usage)
        if error:
            rejected.append(f"multi_chunk: {error}")
            continue
        cases.append(
            TestCase(
                id=next_id(),
                question=result.question,
                ground_truth=result.ground_truth,
                category="multi_chunk",
                relevant_docs=[doc],
                supporting_quotes=[result.supporting_quote_a, result.supporting_quote_b],
            )
        )
    print(f"  {'multi_chunk':16} {sum(c.category == 'multi_chunk' for c in cases):>3}")

    # --- two passages from different papers ---------------------------------
    target = min(TARGETS["multi_document"], args.limit or TARGETS["multi_document"])
    for i in range(target):
        doc_a, doc_b = DOC_PAIRS[i % len(DOC_PAIRS)]
        if doc_a not in corpus or doc_b not in corpus:
            continue
        a, b = rng.choice(corpus[doc_a]), rng.choice(corpus[doc_b])
        result, error = build_pair("multi_document", a, b, usage)
        if error:
            rejected.append(f"multi_document: {error}")
            continue
        cases.append(
            TestCase(
                id=next_id(),
                question=result.question,
                ground_truth=result.ground_truth,
                category="multi_document",
                relevant_docs=[doc_a, doc_b],
                supporting_quotes=[result.supporting_quote_a, result.supporting_quote_b],
            )
        )
    print(f"  {'multi_document':16} {sum(c.category == 'multi_document' for c in cases):>3}")

    # --- hand-written adversarial cases -------------------------------------
    for case in HANDWRITTEN:
        cases.append(
            TestCase(
                id=next_id(),
                question=case.question,
                ground_truth=case.ground_truth,
                category=case.category,
                relevant_docs=list(case.relevant_docs),
                supporting_quotes=list(case.supporting_quotes),
                notes=case.notes,
            )
        )
    print(f"  {'hand-written':16} {len(HANDWRITTEN):>3}")

    save_dataset(cases)
    tokens = sum(r.total_tokens for r in usage.records)
    print(f"\n{len(cases)} cases written to dataset/v1.jsonl")
    print(f"generation used {tokens:,} tokens across {len(usage.records)} calls")
    if rejected:
        print(f"\n{len(rejected)} rejected (quote not verbatim):")
        for reason in rejected:
            print(f"  - {reason}")
    print("\nNext: python -m evaluation.validate_dataset")


if __name__ == "__main__":
    main()
